// -- Vector2D: Clase para operaciones vectoriales en 2D -----------------------
class Vector2D {
  constructor(x = 0, y = 0) {
    this.x = x;
    this.y = y;
  }
  // Crear desde ángulo y magnitud
  static fromAngle(angle, magnitude = 1) {
    return new Vector2D(
      Math.cos(angle) * magnitude,
      Math.sin(angle) * magnitude
    );
  }
  // Suma de vectores
  add(v) {
    return new Vector2D(this.x + v.x, this.y + v.y);
  }
  // Resta de vectores
  subtract(v) {
    return new Vector2D(this.x - v.x, this.y - v.y);
  }
  // Multiplicación por escalar
  multiply(scalar) {
    return new Vector2D(this.x * scalar, this.y * scalar);
  }
  // División por escalar
  divide(scalar) {
    return new Vector2D(this.x / scalar, this.y / scalar);
  }
  // Producto punto
  dot(v) {
    return this.x * v.x + this.y * v.y;
  }
  // Producto cruz (2D retorna escalar z)
  cross(v) {
    return this.x * v.y - this.y * v.x;
  }
  // Magnitud (longitud)
  magnitude() {
    return Math.sqrt(this.x * this.x + this.y * this.y);
  }
  // Magnitud al cuadrado (más eficiente para comparaciones)
  magnitudeSquared() {
    return this.x * this.x + this.y * this.y;
  }
  // Normalizar (vector unitario)
  normalize() {
    const mag = this.magnitude();
    if (mag === 0) return new Vector2D(0, 0);
    return this.divide(mag);
  }
  // Distancia a otro vector
  distanceTo(v) {
    return this.subtract(v).magnitude();
  }
  // Ángulo en radianes
  angle() {
    return Math.atan2(this.y, this.x);
  }
  // Ángulo en grados
  angleDegrees() {
    return this.angle() * (180 / Math.PI);
  }
  // Rotar vector
  rotate(angleRadians) {
    const cos = Math.cos(angleRadians);
    const sin = Math.sin(angleRadians);
    return new Vector2D(
      this.x * cos - this.y * sin,
      this.x * sin + this.y * cos
    );
  }
  // Escalar a una magnitud específica
  scaleTo(magnitude) {
    return this.normalize().multiply(magnitude);
  }
  // Lerp hacia otro vector
  lerp(v, t) {
    return new Vector2D(
      this.x + (v.x - this.x) * t,
      this.y + (v.y - this.y) * t
    );
  }
  // Clonar vector
  clone() {
    return new Vector2D(this.x, this.y);
  }
  // Convertir a string
  toString() {
    return `Vector2D(${this.x.toFixed(2)}, ${this.y.toFixed(2)})`;
  }
}
