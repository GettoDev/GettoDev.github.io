// SDK.js - Abstracción GameMonetize para PALUGO
class SDKManager {
  constructor(options = {}) {
    this.gameId = options.gameId || null;
    this.ready = false;
    this.paused = false;
    this._queue = [];
    this._onPause = options.onPause || (()=>{});
    this._onResume = options.onResume || (()=>{});
    this.debug = !!options.debug;
    this._lastAdTime = 0;
    this._adCooldown = 30000; // 30s cooldown recomendado por AdSense/IMA para evitar VAST 303
    // Silenciar WX VAST 303 en consola (no-fill es normal)
    try {
      window.addEventListener('error', (e) => {
        const msg = String(e.message || e.error?.message || '');
        const stack = String(e.error?.stack || '');
        if (msg.includes('WX') || stack.includes('ima3') || msg.includes('VAST') || stack.includes('VAST')) {
          e.preventDefault();
          if (this.debug) console.warn('[PALUGO SDK] VAST silenciado:', msg);
          return true;
        }
      });
      window.addEventListener('unhandledrejection', (e) => {
        const msg = String(e.reason?.message || e.reason || '');
        if (msg.includes('WX') || msg.includes('VAST') || String(e.reason?.stack||'').includes('ima3')) {
          e.preventDefault();
        }
      });
    } catch {}
    if (options.autoInit !== false) this.init();
  }
  init() {
    if (!this.gameId || this.gameId.includes('YOUR_GAMEMONETIZE') || this.gameId === 'Demo') {
      if (this.debug) console.warn('PALUGO SDK: gameId no configurado (Demo), ads deshabilitados.');
      this.ready = true;
      return;
    }
    if (window.sdk) { this.ready = true; return; }
    // Oficial GameMonetize: window.SDK_OPTIONS + gamemonetize-sdk
    window.SDK_OPTIONS = {
      gameId: this.gameId,
      onEvent: (event) => this._handleEvent(event)
    };
    // Evitar duplicado
    if (document.getElementById('gamemonetize-sdk')) return;
    const script = document.createElement('script');
    script.id = 'gamemonetize-sdk';
    script.src = 'https://api.gamemonetize.com/sdk.js';
    script.async = true;
    script.onload = () => { if (this.debug) console.log('PALUGO SDK loaded', this.gameId); };
    script.onerror = () => console.warn('PALUGO SDK: fallo al cargar sdk.js');
    const first = document.getElementsByTagName('script')[0];
    if (first && first.parentNode) first.parentNode.insertBefore(script, first);
    else document.head.appendChild(script);
    // Timeout fallback: si no responde en 5s, marcar ready para no bloquear juego
    setTimeout(() => { if (!this.ready) { this.ready = true; this._flushQueue(); } }, 5000);
  }
  _handleEvent(event) {
    if (this.debug) console.log('PALUGO SDK Event:', event);
    const name = event && (event.name || event.type || '');
    switch (name) {
      case 'SDK_READY':
        this.ready = true;
        this._flushQueue();
        break;
      case 'SDK_GAME_PAUSE':
        this.paused = true;
        this._onPause();
        // Watchdog de seguridad: no permitir que una pausa de anuncio cuelgue el juego más de 3.5s si no hay respuesta de IMA
        clearTimeout(this._pauseWatchdog);
        this._pauseWatchdog = setTimeout(() => {
          if (this.paused) {
            console.warn('PALUGO SDK: Watchdog timeout tras SDK_GAME_PAUSE, reanudando juego.');
            this.paused = false;
            this._onResume();
          }
        }, 3500);
        break;
      case 'SDK_GAME_START':
      case 'SDK_BANNER_DISMISSED':
      case 'SDK_REWARDED_WATCH_COMPLETE':
        clearTimeout(this._pauseWatchdog);
        this.paused = false;
        this._onResume();
        break;
      case 'SDK_ERROR':
      case 'adLoadError':
      case 'adError':
      default:
        if (name && name.includes('ERROR')) {
          console.warn('PALUGO SDK Event Error:', event);
        }
        clearTimeout(this._pauseWatchdog);
        this.paused = false;
        this._onResume();
        break;
    }
  }
  _flushQueue() {
    while (this._queue.length) {
      const fn = this._queue.shift();
      try { fn(); } catch(e){ console.warn(e); }
    }
  }
  _whenReady(fn) {
    if (this.ready) fn();
    else this._queue.push(fn);
  }
  // Forzar reanudación si quedó pausado
  forceResume() {
    clearTimeout(this._pauseWatchdog);
    this.paused = false;
    try { this._onResume(); } catch {}
  }
  // Interstitial (entre niveles / game over / continue)
  showInterstitial({ onClose, onError } = {}) {
    let closed = false;
    const safeClose = () => {
      if (closed) return;
      closed = true;
      this.forceResume();
      try { onClose?.(); } catch {}
    };
    // Si se activa muy rápido en sucesión (< 15s), omitir llamada directa para evitar error VAST 303 de IMA
    const now = Date.now();
    if (this._lastAdTime && (now - this._lastAdTime < this._adCooldown)) {
      if (this.debug) console.log('PALUGO SDK: Anuncio en cooldown (< 15s), reanudando directamente para evitar VAST 303.');
      safeClose();
      return;
    }
    this._lastAdTime = now;
    // Watchdog de 1.8s garantizado para que nunca se cuelgue el loop
    const timer = setTimeout(safeClose, 1800);
    this._whenReady(() => {
      try {
        if (window.sdk && typeof window.sdk.showBanner === 'function') {
          window.sdk.showBanner();
          safeClose();
        } else if (typeof window.showBanner === 'function') {
          window.showBanner();
          safeClose();
        } else {
          if (this.debug) console.log('[MOCK AD] Interstitial');
          safeClose();
        }
      } catch (e) {
        console.warn('showInterstitial error', e);
        try { onError?.(e); } catch {}
        safeClose();
      } finally {
        clearTimeout(timer);
      }
    });
  }
  // Rewarded (continuar, monedas)
  showRewarded({ onRewarded, onClose, onError } = {}) {
    let handled = false;
    const safeEnd = () => {
      if (handled) return;
      handled = true;
      this.forceResume();
      try { onRewarded?.(); } catch {}
      try { onClose?.(); } catch {}
    };
    const timer = setTimeout(safeEnd, 2000);
    this._whenReady(() => {
      try {
        if (window.sdk && typeof window.sdk.showRewarded === 'function') {
          window.sdk.showRewarded(() => {
            clearTimeout(timer);
            safeEnd();
          });
        } else {
          if (this.debug) console.log('[MOCK AD] Rewarded -> granting reward');
          setTimeout(() => {
            clearTimeout(timer);
            safeEnd();
          }, 300);
        }
      } catch (e) {
        console.warn('showRewarded error', e);
        try { onError?.(e); } catch {}
        safeEnd();
      }
    });
  }
  // Alias legado
  showBanner(...args) { return this.showInterstitial(...args); }
}

