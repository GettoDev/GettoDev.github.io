// Transformar coordenadas locales a mundiales
function localToWorld(localPos, origin, rotation, scale) {
  let pos = localPos.clone();
  if (scale !== 1) pos = pos.multiply(scale);
  if (rotation !== 0) pos = pos.rotate(rotation);
  return pos.add(origin);
}
// Transformar coordenadas mundiales a locales
function worldToLocal(worldPos, origin, rotation, scale) {
  let pos = worldPos.subtract(origin);
  if (rotation !== 0) pos = pos.rotate(-rotation);
  if (scale !== 1) pos = pos.divide(scale);
  return pos;
}
// -- Física simple para colisiones ---------------------------------------------
// Distancia punto a línea
function pointToLineDistance(point, lineStart, lineEnd) {
  const line = lineEnd.subtract(lineStart);
  const len = line.magnitude();
  if (len === 0) return point.distanceTo(lineStart);
  const t = clamp(point.subtract(lineStart).dot(line) / (len * len), 0, 1);
  const projection = lineStart.add(line.multiply(t));
  return point.distanceTo(projection);
}
// Verificar si punto está dentro de círculo
function pointInCircle(point, circleCenter, radius) {
  return point.distanceTo(circleCenter) <= radius;
}
// Verificar si punto está dentro de rectángulo
function pointInRect(point, rectMin, rectMax) {
  return point.x >= rectMin.x && point.x <= rectMax.x &&
         point.y >= rectMin.y && point.y <= rectMax.y;
}
// -- Generadores de patrones matemáticos ---------------------------------------
// Generar puntos en formación de V (apex único, estilo Gradius)
function vFormation(count, spread, depth) {
  const points = [];
  if (count <= 0) return points;
  points.push(new Vector2D(0, 0)); // punta
  for (let i = 1; i < count; i++) {
    const pair = Math.ceil(i / 2); // 1,1,2,2,3...
    const side = (i % 2 === 1) ? 1 : -1; // impar arriba, par abajo
    points.push(new Vector2D(pair * depth, side * pair * spread));
  }
  return points;
}
// Generar puntos en formación de línea
function lineFormation(count, spacing, offset = 0) {
  const points = [];
  for (let i = 0; i < count; i++) {
    points.push(new Vector2D(i * spacing + offset, 0));
  }
  return points;
}
// Generar puntos en formación de círculo
function circleFormation(count, radius) {
  const points = [];
  for (let i = 0; i < count; i++) {
    const angle = (i / count) * Math.PI * 2;
    points.push(new Vector2D(
      Math.cos(angle) * radius,
      Math.sin(angle) * radius
    ));
  }
  return points;
}
// Generar puntos en formación de grid
function gridFormation(rows, cols, spacingX, spacingY) {
  const points = [];
  for (let row = 0; row < rows; row++) {
    for (let col = 0; col < cols; col++) {
      points.push(new Vector2D(
        col * spacingX,
        row * spacingY
      ));
    }
  }
  return points;
}

