// Interpolación lineal (Lerp)
function lerp(a, b, t) {
  return a + (b - a) * t;
}
// Lerp para vectores
function lerpVector(v1, v2, t) {
  return v1.lerp(v2, t);
}
// Lerp con clamp (t entre 0 y 1)
function lerpClamped(a, b, t) {
  t = Math.max(0, Math.min(1, t));
  return a + (b - a) * t;
}
// Interpolación suave (Smoothstep)
function smoothstep(t) {
  return t * t * (3 - 2 * t);
}
// Interpolación más suave (Smootherstep)
function smootherstep(t) {
  return t * t * t * (t * (t * 6 - 15) + 10);
}
// Interpolación sinusoidal
function sinusoidal(t) {
  return (1 - Math.cos(t * Math.PI)) / 2;
}
// -- Curvas Bézier -------------------------------------------------------------
// Curva Bézier lineal (2 puntos)
function bezierLinear(p0, p1, t) {
  return new Vector2D(
    lerp(p0.x, p1.x, t),
    lerp(p0.y, p1.y, t)
  );
}
// Curva Bézier cuadrática (3 puntos)
function bezierQuadratic(p0, p1, p2, t) {
  const mt = 1 - t;
  return new Vector2D(
    mt * mt * p0.x + 2 * mt * t * p1.x + t * t * p2.x,
    mt * mt * p0.y + 2 * mt * t * p1.y + t * t * p2.y
  );
}
// Curva Bézier cúbica (4 puntos)
function bezierCubic(p0, p1, p2, p3, t) {
  const mt = 1 - t;
  const mt2 = mt * mt;
  const mt3 = mt2 * mt;
  const t2 = t * t;
  const t3 = t2 * t;
  return new Vector2D(
    mt3 * p0.x + 3 * mt2 * t * p1.x + 3 * mt * t2 * p2.x + t3 * p3.x,
    mt3 * p0.y + 3 * mt2 * t * p1.y + 3 * mt * t2 * p2.y + t3 * p3.y
  );
}
// Curva Bézier general (n puntos)
function bezierGeneral(points, t) {
  if (points.length === 0) return new Vector2D(0, 0);
  if (points.length === 1) return points[0].clone();
  let result = points.map(p => p.clone());
  for (let k = 1; k < points.length; k++) {
    for (let i = 0; i < points.length - k; i++) {
      result[i] = result[i].lerp(result[i + 1], t);
    }
  }
  return result[0];
}
// Obtener puntos discretos de una curva Bézier
function bezierPoints(points, numSegments = 20) {
  const result = [];
  for (let i = 0; i <= numSegments; i++) {
    const t = i / numSegments;
    result.push(bezierGeneral(points, t));
  }
  return result;
}
