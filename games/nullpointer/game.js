// Normalizar ángulo a rango [-π, π]
function normalizeAngle(angle) {
  while (angle > Math.PI) angle -= 2 * Math.PI;
  while (angle < -Math.PI) angle += 2 * Math.PI;
  return angle;
}
// Diferencia angular más corta entre dos ángulos
