  // -- Anti-superposición: separación suave entre enemigos solapados --
  _applyEnemySeparation(dt) {
    const PAD = 4;
    const MAX_ITERS = 2;
    for (let iter = 0; iter < MAX_ITERS; iter++) {
      let moved = false;
      for (let i = 0; i < this.enemies.length; i++) {
        for (let j = i + 1; j < this.enemies.length; j++) {
          const a = this.enemies[i], b = this.enemies[j];
          if (a.pattern === 'interceptor_worm' || b.pattern === 'interceptor_worm' || a.isMiniboss || b.isMiniboss) continue;
          const ax = a.x + a.w/2, ay = a.y + a.h/2;
          const bx = b.x + b.w/2, by = b.y + b.h/2;
          const dx = ax - bx, dy = ay - by;
          // solo si están cerca horizontalmente (misma zona de pantalla)
          if (Math.abs(dx) > (a.w + b.w)/2 + 24) continue;
          const needY = (a.h + b.h)/2 + PAD;
          if (Math.abs(dy) >= needY) continue;
          const overlap = needY - Math.abs(dy);
          if (overlap <= 0.1) continue;
          // empujar verticalmente (el de arriba hacia arriba, el de abajo hacia abajo)
          const push = (overlap/2 + 1.2) * Math.min(1, dt*60);
          if (ay < by) {
            a.y -= push; b.y += push;
            if (a.pattern==='sine') a.baseY -= push;
            if (b.pattern==='sine') b.baseY += push;
            // añadir vy repulsivo para zigzag/hunter para evitar reconvergencia inmediata
            if (a.pattern==='zigzag') a.vy = Math.min(a.vy - 8, -15);
            if (b.pattern==='zigzag') b.vy = Math.max(b.vy + 8, 15);
          } else {
            a.y += push; b.y -= push;
            if (a.pattern==='sine') a.baseY += push;
            if (b.pattern==='sine') b.baseY -= push;
            if (a.pattern==='zigzag') a.vy = Math.max(a.vy + 8, 15);
            if (b.pattern==='zigzag') b.vy = Math.min(b.vy - 8, -15);
          }
          // clamp inmediato al gap para no salir
          const gapA = this.getGapAtX(a.x + a.w/2);
          const gapB = this.getGapAtX(b.x + b.w/2);
          a.y = Math.max(gapA.top+2, Math.min(gapA.bottom - a.h -2, a.y));
          b.y = Math.max(gapB.top+2, Math.min(gapB.bottom - b.h -2, b.y));
          if (a.pattern==='sine') a.baseY = Math.max(gapA.top+2, Math.min(gapA.bottom - a.h -2, a.baseY));
          if (b.pattern==='sine') b.baseY = Math.max(gapB.top+2, Math.min(gapB.bottom - b.h -2, b.baseY));
          moved = true;
        }
      }
      if (!moved) break;
    }
  }
