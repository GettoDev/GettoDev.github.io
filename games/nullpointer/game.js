// Input.js - Teclado PALUGO (sin táctil, táctil separado en TouchControls.js para Android)
class Input {
  constructor(options = {}) {
    this.turboRate = options.turboRate || 10;
    this._turboPhase = false;
    this._turboTimer = 0;
    this.state = {
      up: false, down: false, left: false, right: false,
      btnA: false, btnB: false,
      turboA: false, turboB: false,
      btnStart: false
    };
    this._prev = { ...this._resolvedState() };
    this._cur = { ...this._resolvedState() };
    this.keyMap = {
      ArrowUp: 'up', KeyW: 'up',
      ArrowDown: 'down', KeyS: 'down',
      ArrowLeft: 'left', KeyA: 'left',
      ArrowRight: 'right', KeyD: 'right',
      KeyJ: 'btnA',
      KeyK: 'btnB',
      KeyU: 'turboA',
      KeyI: 'turboB',
      Enter: 'btnStart', Space: 'btnStart',
      ShiftLeft: 'btnStart', ShiftRight: 'btnStart'
    };
    this._initKeyboard();
  }
  _initKeyboard() {
    window.addEventListener('keydown', (e) => {
      const key = this.keyMap[e.code];
      if (key) {
        if (['ArrowUp','ArrowDown','ArrowLeft','ArrowRight','Space'].includes(e.code)) e.preventDefault();
        this.state[key] = true;
      }
    });
    window.addEventListener('keyup', (e) => {
      const key = this.keyMap[e.code];
      if (key) this.state[key] = false;
    });
    window.addEventListener('blur', () => {
      for (const k of Object.keys(this.state)) this.state[k] = false;
    });
  }
  update(dt) {
    this._prev = { ...this._cur };
    this._turboTimer += dt;
    const period = 1 / this.turboRate;
    if (this._turboTimer >= period / 2) {
      this._turboPhase = !this._turboPhase;
      this._turboTimer = 0;
    }
    this._cur = { ...this._resolvedState() };
  }
  _resolvedState() {
    return {
      up: this.state.up,
      down: this.state.down,
      left: this.state.left,
      right: this.state.right,
      btnA: this.state.btnA || (this.state.turboA && this._turboPhase),
      btnB: this.state.btnB || (this.state.turboB && this._turboPhase),
      turboA: this.state.turboA,
      turboB: this.state.turboB,
      btnStart: this.state.btnStart,
      rawA: this.state.btnA,
      rawB: this.state.btnB
    };
  }
  getState() { return { ...this._cur }; }
  justPressed(key) { return this._cur[key] && !this._prev[key]; }
  justReleased(key) { return !this._cur[key] && this._prev[key]; }
  destroy() {}
}

