// Audio.js - PALUGO NES-like 4-channel synth (Pulse1, Pulse2, Triangle, Noise) + buses música/SFX
// v2.1 - Gesture-safe AudioContext (never auto-create before user input)
class PalugoAudio {
  constructor(options = {}) {
    this.masterVolume = options.masterVolume ?? 0.16;
    this.musicVolume = options.musicVolume ?? 0.9;
    this.sfxVolume = options.sfxVolume ?? 1.0;
    this.ctx = null;
    this.masterGain = null;
    this.musicGain = null;
    this.sfxGain = null;
    this.channelGains = { pulse1: null, pulse2: null, triangle: null, noise: null };
    this._pulseDuty = options.pulseDuty ?? 0.5;
    this._readyCbs = [];
    this._unlockBound = this._unlock.bind(this);
    // Register gesture listeners immediately - init() fires on first user action
    window.addEventListener('pointerdown', this._unlockBound, { once: true, passive: true });
    window.addEventListener('keydown',     this._unlockBound, { once: true, passive: true });
    window.addEventListener('touchstart',  this._unlockBound, { once: true, passive: true });
  }
  // Called on first user gesture - creates AudioContext and fires queued callbacks
  _unlock() {
    window.removeEventListener('pointerdown', this._unlockBound);
    window.removeEventListener('keydown',     this._unlockBound);
    window.removeEventListener('touchstart',  this._unlockBound);
    this.init();
    const cbs = this._readyCbs.splice(0);
    cbs.forEach(cb => { try { cb(); } catch {} });
  }
  init() {
    if (this.ctx) {
      if (this.ctx.state === 'suspended') {
        this.ctx.resume().catch(() => {});
      }
      return true;
    }
    const AC = window.AudioContext || window.webkitAudioContext;
    if (!AC) return false;
    try {
      this.ctx = new AC();
      this.masterGain = this.ctx.createGain();
      this.masterGain.gain.value = this.masterVolume;
      this.masterGain.connect(this.ctx.destination);
      this.musicGain = this.ctx.createGain();
      this.musicGain.gain.value = this.musicVolume;
      this.musicGain.connect(this.masterGain);
      this.sfxGain = this.ctx.createGain();
      this.sfxGain.gain.value = this.sfxVolume;
      this.sfxGain.connect(this.masterGain);
      for (const ch of ['pulse1','pulse2','triangle','noise']) {
        const g = this.ctx.createGain();
        g.gain.value = 1;
        g.connect(this.sfxGain);
        this.channelGains[ch] = g;
      }
      // Pre-generar buffers de ruido (1 segundo) para evitar allocs en cada golpe de batería
      const sr = this.ctx.sampleRate;
      this._noiseBuffer = this.ctx.createBuffer(1, sr, sr);
      const ndata = this._noiseBuffer.getChannelData(0);
      for (let i = 0; i < sr; i++) ndata[i] = Math.random() * 2 - 1;
      this._metallicBuffer = this.ctx.createBuffer(1, sr, sr);
      const mdata = this._metallicBuffer.getChannelData(0);
      let last = 0;
      for (let i = 0; i < sr; i++) {
        last = (last + Math.random()) % 2 > 1 ? 1 : -1;
        mdata[i] = last * (Math.random() * 0.5 + 0.5);
      }
      return true;
    } catch {
      return false;
    }
  }
  // Returns true only when AudioContext exists AND is actively running
  isReady() {
    return !!(this.ctx && this.ctx.state === 'running');
  }
  // Calls cb() immediately if ready, or queues it for first gesture unlock
  onReady(cb) {
    if (this.isReady()) { cb(); return; }
    this._readyCbs.push(cb);
  }
  // NEVER calls init() - prevents AudioContext before user gesture
  _ensure() {
    return this.isReady();
  }
  setMasterVolume(v) {
    this.masterVolume = Math.max(0, Math.min(1, v));
    if (this.masterGain && this.ctx) {
      try {
        this.masterGain.gain.cancelScheduledValues(this.ctx.currentTime);
        this.masterGain.gain.setValueAtTime(this.masterVolume, this.ctx.currentTime);
      } catch {}
    }
  }
  setMusicVolume(v) {
    this.musicVolume = Math.max(0, Math.min(1.2, v));
    if (this.musicGain && this.ctx) {
      try {
        this.musicGain.gain.cancelScheduledValues(this.ctx.currentTime);
        this.musicGain.gain.setValueAtTime(this.musicVolume, this.ctx.currentTime);
      } catch {}
    }
  }
  setSfxVolume(v) {
    this.sfxVolume = Math.max(0, Math.min(1, v));
    if (this.sfxGain && this.ctx) {
      try {
        this.sfxGain.gain.cancelScheduledValues(this.ctx.currentTime);
        this.sfxGain.gain.setValueAtTime(this.sfxVolume, this.ctx.currentTime);
      } catch {}
    }
  }
  // Compat: setVolumes 0-100
  setVolumes(music01, sfx01) {
    this.setMusicVolume(music01);
    this.setSfxVolume(sfx01);
  }
  mute(muted = true) {
    if (this.masterGain && this.ctx) {
      try {
        this.masterGain.gain.cancelScheduledValues(this.ctx.currentTime);
        this.masterGain.gain.setValueAtTime(muted ? 0 : this.masterVolume, this.ctx.currentTime);
      } catch {}
    }
  }
  _targetBus(isMusic) {
    if (!this.musicGain || !this.sfxGain) return this.masterGain;
    return isMusic ? this.musicGain : this.sfxGain;
  }
  _playPulse(channel, freq, { duration = 0.12, volume = 0.15, duty = 0.5, slide = 0, isMusic = false } = {}) {
    if (!this._ensure()) return;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();
    if (duty !== 0.5 && duty !== 0) {
      try {
        const wave = this._createPulseWave(duty);
        osc.setPeriodicWave(wave);
      } catch { osc.type = 'square'; }
    } else {
      osc.type = 'square';
    }
    osc.frequency.setValueAtTime(freq, this.ctx.currentTime);
    if (slide) osc.frequency.linearRampToValueAtTime(freq + slide, this.ctx.currentTime + duration);
    gain.gain.setValueAtTime(volume, this.ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.0001, this.ctx.currentTime + duration);
    osc.connect(gain);
    gain.connect(this._targetBus(isMusic));
    osc.start();
    osc.stop(this.ctx.currentTime + duration);
    return osc;
  }
  playPulse1(freq, opts = {}) { return this._playPulse('pulse1', freq, opts); }
  playPulse2(freq, opts = {}) { return this._playPulse('pulse2', freq, opts); }
  playTriangle(freq, { duration = 0.12, volume = 0.18, isMusic = false } = {}) {
    if (!this._ensure()) return;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();
    osc.type = 'triangle';
    osc.frequency.setValueAtTime(freq, this.ctx.currentTime);
    gain.gain.setValueAtTime(volume * 0.7, this.ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.0001, this.ctx.currentTime + duration);
    osc.connect(gain);
    gain.connect(this._targetBus(isMusic));
    osc.start();
    osc.stop(this.ctx.currentTime + duration);
    return osc;
  }
  playNoise({ duration = 0.12, volume = 0.12, metallic = false, isMusic = false } = {}) {
    if (!this._ensure()) return;
    const src = this.ctx.createBufferSource();
    src.buffer = (metallic ? this._metallicBuffer : this._noiseBuffer) || this.ctx.createBuffer(1, 256, this.ctx.sampleRate);
    src.loop = true;
    const gain = this.ctx.createGain();
    const filter = this.ctx.createBiquadFilter();
    filter.type = 'highpass';
    filter.frequency.value = 800;
    gain.gain.setValueAtTime(volume, this.ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.0001, this.ctx.currentTime + duration);
    src.connect(filter);
    filter.connect(gain);
    gain.connect(this._targetBus(isMusic));
    src.start();
    src.stop(this.ctx.currentTime + duration);
    return src;
  }
  schedulePulse(channel, freq, startTime, duration, { volume = 0.15, duty = 0.5, slide = 0, isMusic = true } = {}) {
    if (!this._ensure() || freq <= 0) return null;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();
    if (duty !== 0.5 && duty !== 0) {
      try {
        const wave = this._createPulseWave(duty);
        osc.setPeriodicWave(wave);
      } catch { osc.type = 'square'; }
    } else {
      osc.type = 'square';
    }
    const t0 = Math.max(this.ctx.currentTime, startTime);
    osc.frequency.setValueAtTime(freq, t0);
    if (slide) osc.frequency.linearRampToValueAtTime(freq + slide, t0 + duration);
    gain.gain.setValueAtTime(volume, t0);
    gain.gain.exponentialRampToValueAtTime(0.0001, t0 + duration);
    osc.connect(gain);
    gain.connect(this._targetBus(isMusic));
    osc.start(t0);
    osc.stop(t0 + duration);
    return osc;
  }
  scheduleTriangle(freq, startTime, duration, { volume = 0.18, isMusic = true } = {}) {
    if (!this._ensure() || freq <= 0) return null;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();
    osc.type = 'triangle';
    const t0 = Math.max(this.ctx.currentTime, startTime);
    osc.frequency.setValueAtTime(freq, t0);
    gain.gain.setValueAtTime(volume * 0.75, t0);
    gain.gain.exponentialRampToValueAtTime(0.0001, t0 + duration);
    osc.connect(gain);
    gain.connect(this._targetBus(isMusic));
    osc.start(t0);
    osc.stop(t0 + duration);
    return osc;
  }
  scheduleNoise(startTime, duration, { volume = 0.12, metallic = false, isMusic = true } = {}) {
    if (!this._ensure() || duration <= 0) return null;
    const src = this.ctx.createBufferSource();
    src.buffer = (metallic ? this._metallicBuffer : this._noiseBuffer) || this.ctx.createBuffer(1, 256, this.ctx.sampleRate);
    src.loop = true;
    const gain = this.ctx.createGain();
    const filter = this.ctx.createBiquadFilter();
    filter.type = 'highpass';
    filter.frequency.value = 750;
    const t0 = Math.max(this.ctx.currentTime, startTime);
    gain.gain.setValueAtTime(volume, t0);
    gain.gain.exponentialRampToValueAtTime(0.0001, t0 + duration);
    src.connect(filter);
    filter.connect(gain);
    gain.connect(this._targetBus(isMusic));
    src.start(t0);
    src.stop(t0 + duration);
    return src;
  }
  playTone(freq, type = 'square', duration = 0.1, volume = 0.1) {
    if (type === 'triangle') return this.playTriangle(freq, { duration, volume, isMusic: false });
    if (type === 'square') return this.playPulse1(freq, { duration, volume, isMusic: false });
    return this._playPulse('pulse1', freq, { duration, volume, isMusic: false });
  }
  sfxJump()      { this.playPulse1(300, { duration:0.12, volume:0.18 }); this.playPulse2(600, { duration:0.08, volume:0.12 }); }
  sfxCoin()      { this.playPulse1(880, { duration:0.10, volume:0.15 }); setTimeout(()=>this.playPulse1(1200,{duration:0.15,volume:0.14}),80); }
  sfxHit()       { this.playNoise({ duration:0.08, volume:0.20 }); this.playPulse1(120,{duration:0.06, volume:0.2}); }
  sfxExplosion() { this.playNoise({ duration:0.35, volume:0.22 }); }
  sfxLaser()     { this.playPulse1(800,{duration:0.08, volume:0.15, slide:-400}); }
  sfxSelect()    { this.playPulse1(600,{duration:0.08, volume:0.14}); }
  sfxBack()      { this.playPulse1(300,{duration:0.08, volume:0.14, slide:-100}); }
  playSequence(notes, tempo = 120, isMusic = true) {
    if (!this._ensure()) return;
    const beatSec = 60 / tempo;
    let t = this.ctx.currentTime + 0.03;
    notes.forEach(n => {
      const dur = (n.durationBeats || 1) * beatSec;
      const vol = n.volume ?? 0.12;
      const ch = n.channel;
      const freq = n.freq;
      const useMusic = n.isMusic ?? isMusic;
      const duty = n.duty ?? 0.5;
      const slide = n.slide ?? 0;
      if (freq > 0) {
        if (ch === 'triangle') this.scheduleTriangle(freq, t, dur * 0.92, { volume: vol, isMusic: useMusic });
        else if (ch === 'noise') this.scheduleNoise(t, dur * 0.92, { volume: vol, isMusic: useMusic });
        else this.schedulePulse(ch || 'pulse1', freq, t, dur * 0.92, { volume: vol, duty, slide, isMusic: useMusic });
      } else if (ch === 'noise' && n.isNoiseHit) {
        this.scheduleNoise(t, dur * 0.92, { volume: vol, isMusic: useMusic });
      }
      t += dur;
    });
  }
  _createPulseWave(duty) {
    const real = new Float32Array(8);
    const imag = new Float32Array(8);
    for (let n = 1; n < 8; n++) {
      const a = (2 / (Math.PI * n)) * Math.sin(Math.PI * n * duty);
      imag[n] = a;
    }
    return this.ctx.createPeriodicWave(real, imag, { disableNormalization: false });
  }
}
