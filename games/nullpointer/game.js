class ArcMovementCommand extends PatternCommand {
  constructor(startAngle, endAngle, radius, speed, centerX, centerY, duration){
    super(); this.startAngle=startAngle*(Math.PI/180); this.endAngle=endAngle*(Math.PI/180); this.radius=radius; this.speed=speed; this.centerX=centerX; this.centerY=centerY; this.duration=duration; this.elapsed=0; this._started=false; this.currentAngle=this.startAngle;
  }
  execute(enemy, context, dt){
    if(!this._started){
      // si centro absoluto lejos, recentrar relativo al enemigo
      const d=Math.hypot(enemy.x-this.centerX, enemy.y-this.centerY);
      if(d>this.radius*3){ this.centerX=enemy.x; this.centerY=enemy.y; }
      this.currentAngle=Math.atan2(enemy.y-this.centerY, enemy.x-this.centerX);
      this._started=true;
    }
    const angularSpeed=this.speed/this.radius;
    this.currentAngle+=angularSpeed*dt;
    enemy.x=this.centerX+Math.cos(this.currentAngle)*this.radius;
    enemy.y=this.centerY+Math.sin(this.currentAngle)*this.radius;
    this.elapsed+=dt;
  }
  isComplete(){ return this.duration!==null && this.elapsed>=this.duration; }
}
class FanAttackCommand extends PatternCommand {
  constructor(centerAngle, spreadAngle, bulletCount, bulletSpeed, interval){
    super(); this.centerAngle=centerAngle*(Math.PI/180); this.spreadAngle=spreadAngle*(Math.PI/180); this.bulletCount=bulletCount; this.bulletSpeed=bulletSpeed; this.interval=interval; this.fired=0; this.lastFire=0;
  }
  execute(enemy, context, dt){
    this.lastFire+=dt;
    if(this.fired<this.bulletCount && this.lastFire>=this.interval){
      const t=this.fired/(this.bulletCount-1||1);
      const angle=this.centerAngle+(t-0.5)*this.spreadAngle;
      context.spawnProjectile(enemy.x+enemy.w/2, enemy.y+enemy.h/2, Math.cos(angle)*this.bulletSpeed, Math.sin(angle)*this.bulletSpeed);
      this.fired++; this.lastFire=0;
    }
  }
  isComplete(){ return this.fired>=this.bulletCount; }
}
class ZigzagBezierCommand extends PatternCommand {
  // ahora interpreta controlPoints como OFFSETS relativos al startPos, no absolutos
  constructor(controlPoints, speed, duration){ super(); this.controlPoints=controlPoints; this.speed=speed; this.duration=duration; this.elapsed=0; this._started=false; this.startPos={x:0,y:0}; this._isAbsolute=false; }
  execute(enemy, context, dt){
    if(!this._started){
      this.startPos={x:enemy.x,y:enemy.y};
      // detectar si puntos son absolutos (x > 400) -> convertir a deltas
      if(this.controlPoints.length>0 && this.controlPoints[0].x>300 && Math.abs(this.controlPoints[0].x-enemy.x)>200){
        this._isAbsolute=true;
      }
      this._started=true;
    }
    this.elapsed+=dt;
    const t=Math.min(1,this.elapsed/this.duration);
    if(this._isAbsolute){
      // interpolar entre puntos absolutos
      const idx=Math.floor(t*(this.controlPoints.length-1));
      const n=Math.min(idx+1,this.controlPoints.length-1);
      const localT=(t*(this.controlPoints.length-1))-idx;
      const p0=this.controlPoints[idx], p1=this.controlPoints[n];
      enemy.x= p0.x+(p1.x-p0.x)*localT;
      enemy.y= p0.y+(p1.y-p0.y)*localT;
    } else {
      // offsets relativos: enemy se mueve -speed*dt en X + lerp Y entre offsets
      const pts=this.controlPoints;
      const segT=t*(pts.length-1);
      const idx=Math.min(Math.floor(segT), pts.length-2);
      const frac=segT-idx;
      const p0=pts[idx], p1=pts[idx+1];
      const offX=p0.x+(p1.x-p0.x)*frac;
      const offY=p0.y+(p1.y-p0.y)*frac;
      // mantener progresión izquierda
      enemy.x=this.startPos.x - this.speed*this.elapsed + offX;
      enemy.y=this.startPos.y + offY;
    }
  }
  distance(p1,p2){ return Math.hypot(p2.x-p1.x,p2.y-p1.y); }
  isComplete(){ return this.elapsed>=this.duration; }
}
class RetreatCommand extends PatternCommand {
  constructor(distance,speed,duration){ super(); this.distance=distance; this.speed=speed; this.duration=duration; this.elapsed=0; this.startX=0; this._started=false; }
  execute(enemy,c,dt){ if(!this._started){ this.startX=enemy.x; this._started=true; } enemy.x-=this.speed*dt; this.elapsed+=dt; }
  isComplete(){ return this.elapsed>=this.duration || (this.startX-enemy.x)>=this.distance; }
}
class PatternInterpreter {
  constructor(){ this.commands=[]; this.currentCommand=0; this.context=null; }
  loadCommands(cmds){ this.commands=cmds; this.currentCommand=0; }
  setContext(ctx){ this.context=ctx; }
  execute(enemy, dt){
    if(this.currentCommand>=this.commands.length) return false;
    const cmd=this.commands[this.currentCommand];
    cmd.execute(enemy,this.context,dt);
    if(cmd.isComplete(enemy,this.context)) this.currentCommand++;
    return true;
  }
  reset(){
    this.currentCommand=0;
    for(const c of this.commands){ if(c.elapsed!==undefined) c.elapsed=0; if(c.executed!==undefined) c.executed=false; if(c.fired!==undefined){ c.fired=0; c.lastFire=0; } if(c._started!==undefined) c._started=false; if(c.segment!==undefined){ c.segment=0; c.segmentProgress=0; } }
  }
  isComplete(){ return this.currentCommand>=this.commands.length; }
}
