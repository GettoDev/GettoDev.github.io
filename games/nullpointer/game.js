class ProceduralWaveGenerator {
  constructor(spawnSystem){
    this.spawnSystem = spawnSystem;
    this.difficulty = 1.0;
    this.waveCount = 0;
    this.cooldown = 0; // segundos hasta próxima oleada
  }
  // secuencia curada estilo Gradius stage 1 / R-Type stage 1
  _pickPattern(){
    this.waveCount++;
    this.difficulty = 1.0 + this.waveCount * 0.06;
    // cada 9 oleadas carrier garantizado
    if (this.waveCount % 9 === 0) return 'carrier_wave';
    if (this.waveCount <= 12) {
      const seq = [
        'gradius_v_rush',       // 1
        'rtype_wave_column',    // 2
        'dart_echelon',         // 3
        'gradius_v_rush',       // 4
        'wall_row',             // 5
        'interceptor_advanced', // 6
        'rtype_wave_column',    // 7
        'hunter_pair',          // 8
        'carrier_wave',         // 9
        'bomber_train',         // 10
        'interceptor_squadron', // 11
        'heavy_escort',         // 12
      ];
      return seq[this.waveCount-1];
    }
    // después: ponderado sin lista fija
    const r = Math.random();
    if (r < 0.22) return 'gradius_v_rush';
    if (r < 0.38) return 'rtype_wave_column';
    if (r < 0.52) return 'dart_echelon';
    if (r < 0.64) return 'wall_row';
    if (r < 0.74) return 'hunter_pair';
    if (r < 0.84) return 'bomber_train';
    if (r < 0.91) return 'heavy_escort';
    if (r < 0.96) return 'interceptor_advanced';
    return 'interceptor_squadron';
  }
  generateWave(){
    const name = this._pickPattern();
    const pat = this.spawnSystem.getPattern(name);
    if (!pat) return name;
    // delay entre oleadas: 1.4s base, baja con dificultad hasta 0.9s
    const delay = Math.max(0.9, 1.55 - this.difficulty*0.08) + Math.random()*0.35;
    this.spawnSystem.scheduleWave(name, 0.15); // 150ms de anticipación, no delay largo
    this.cooldown = delay;
    return name;
  }
  shouldGenerateWave(){ return this.cooldown <= 0; }
  tick(dt){ if(this.cooldown>0) this.cooldown-=dt; }
  reset(){ this.difficulty=1.0; this.waveCount=0; this.cooldown=0; }
}

