// -- Sistema de Power-Ups (estilo Gradius) -------------------------------------
// Barra inferior con 6 slots fijos; cada cápsula recogida avanza el cursor 1 pos.
// K activa el slot resaltado → efecto aplicado → cursor vuelve a -1.
const PW_SLOTS  = ['SPEEDUP', 'MISSILE', 'DOUBLE', 'LASER', 'OPTION', '?'];
const PW_COUNT  = PW_SLOTS.length; // 6
class PowerUpSystem {
  constructor() {
    this.reset();
  }
  // Resetea todos los powerups y el cursor (se usa al perder todas las vidas / GameOver o nueva partida)
  reset() {
    this.cursor       = -1;    // sin slot seleccionado al inicio (-1)
    this.effects = {
      speedLevel:   0,         // +35 vel/stack, máx 3
      missileLevel: 0,         // 0: ninguno, 1: abajo, 2: abajo + arriba (2 en total)
      hasDouble:    false,     // disparo adicional arriba
      laserActive:  false,     // láser ancho
      laserTimer:   0,         // segundos restantes
      optionCount:  0,         // orbes activos (0-2)
    };
    this.options      = [];    // orbes OPTION: [{x,y,histX[],histY[]}]
    this.missiles     = [];    // balas misil en vuelo
    this.missileTimer = 0;
  }
  // Avanza cursor al recoger una cápsula
  advance() {
    if (this.cursor === -1) {
      this.cursor = 0;
    } else {
      this.cursor = (this.cursor + 1) % PW_COUNT;
    }
  }
  // Activa el power-up del slot actual y resetea cursor a -1
  activate(game) {
    if (this.cursor < 0 || this.cursor >= PW_COUNT) return;
    const slot = PW_SLOTS[this.cursor];
    switch (slot) {
      case 'SPEEDUP':
        this.effects.speedLevel = Math.min(3, this.effects.speedLevel + 1);
        game.engine.audio.playPulse1(660, { duration:0.15, volume:0.22, slide:220, duty:0.25, isMusic:false });
        break;
      case 'MISSILE':
        // 1ª activación: misil hacia abajo. 2ª activación: misil hacia abajo + misil hacia arriba (2 en total)
        this.effects.missileLevel = Math.min(2, this.effects.missileLevel + 1);
        game.engine.audio.playPulse1(440 + this.effects.missileLevel * 120, { duration:0.14, volume:0.20, duty:0.5, isMusic:false });
        break;
      case 'DOUBLE':
        this.effects.hasDouble  = true;
        game.engine.audio.playPulse1(550, { duration:0.10, volume:0.18, duty:0.25, isMusic:false });
        break;
      case 'LASER':
        this.effects.laserActive = true;
        this.effects.laserTimer  = 15;
        game.engine.audio.playPulse1(880, { duration:0.18, volume:0.22, slide:400, duty:0.125, isMusic:false });
        break;
      case 'OPTION':
        if (this.effects.optionCount < 2) {
          this.effects.optionCount++;
          const trailLen = 80;
          this.options.push({
            x:    game.ship.x - 50,
            y:    game.ship.y + 14,
            histX: new Array(trailLen).fill(game.ship.x - 50),
            histY: new Array(trailLen).fill(game.ship.y + 14),
          });
          game.engine.audio.sfxCoin();
        }
        break;
      case '?':
        if (Math.random() < 0.5) {
          this.effects.speedLevel = Math.min(3, this.effects.speedLevel + 1);
          game.engine.audio.playPulse1(660, { duration:0.15, volume:0.22, slide:220, duty:0.25, isMusic:false });
        } else {
          // Screen clear
          const bonus = game.enemies.reduce((s, e) => s + e.score, 0);
          for (const e of game.enemies) {
            game.explode(e.x + e.w / 2, e.y + e.h / 2, e.color, 7);
          }
          game.score  += bonus;
          game.enemies = [];
          game.engine.audio.sfxExplosion();
        }
        break;
    }
    this.cursor = -1;
  }
  // Llama cada frame
  update(dt, ship) {
    // Countdown laser
    if (this.effects.laserActive) {
      this.effects.laserTimer -= dt;
      if (this.effects.laserTimer <= 0) {
        this.effects.laserActive = false;
        this.effects.laserTimer  = 0;
      }
    }
    // Orbes OPTION siguen el trail de la nave
    for (let oi = 0; oi < this.options.length; oi++) {
      const opt = this.options[oi];
      opt.histX.push(ship.x + 26); opt.histY.push(ship.y + 14);
      if (opt.histX.length > 80) { opt.histX.shift(); opt.histY.shift(); }
      const delay = 55 + oi * 22;
      const idx   = Math.max(0, opt.histX.length - 1 - delay);
      opt.x = opt.histX[idx];
      opt.y = opt.histY[idx];
    }
    // Timer auto-misil
    if (this.effects.missileLevel > 0) {
      this.missileTimer += dt;
    }
    // Actualizar misiles en vuelo
    for (const m of this.missiles) {
      m.x  += m.vx * dt;
      m.y  += m.vy * dt;
      m.life -= dt;
    }
    this.missiles = this.missiles.filter(m => m.life > 0 && m.x < 700 && m.y > 0 && m.y < 500);
  }
  // ¿Toca disparar misil automático?
  shouldFireMissile() {
    if (this.effects.missileLevel <= 0) return false;
    if (this.missileTimer >= 1.30) { this.missileTimer = 0; return true; }
    return false;
  }
  // Spawn de misil diagonal (1ª activación: abajo; 2ª activación: abajo y arriba)
  spawnMissile(x, y) {
    // 1ª activación: 1 misil hacia abajo
    if (this.effects.missileLevel >= 1) {
      this.missiles.push({ x, y: y + 4, vx: 320, vy: 110, life: 4.5, w: 6, h: 3, isMissile: true });
    }
    // 2ª activación: agrega misil hacia arriba (2 en total)
    if (this.effects.missileLevel >= 2) {
      this.missiles.push({ x, y: y - 4, vx: 320, vy: -110, life: 4.5, w: 6, h: 3, isMissile: true });
    }
  }
}
